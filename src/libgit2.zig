//! Deliberately small, stable libgit2 1.9 ABI. Ownership stays in git.zig.
pub const Repository = opaque {};
pub const Reference = opaque {};
pub const Commit = opaque {};
pub const Tree = opaque {};
pub const Revwalk = opaque {};
pub const Diff = opaque {};
pub const Patch = opaque {};
pub const Remote = opaque {};
pub const Oid = extern struct { id: [20]u8 };
pub const Buffer = extern struct { ptr: ?[*]u8 = null, reserved: usize = 0, size: usize = 0 };
pub const Error = extern struct { message: ?[*:0]const u8, klass: c_int };
pub const Strarray = extern struct { strings: ?[*][*:0]u8 = null, count: usize = 0 };
pub const Time = extern struct { time: i64, offset: c_int, sign: u8 };
pub const Signature = extern struct { name: [*:0]const u8, email: [*:0]const u8, when: Time };
pub const DiffFile = extern struct { id: Oid, path: ?[*:0]const u8, size: u64, flags: u32, mode: u16, id_abbrev: u16 };
pub const Delta = extern struct { status: c_int, flags: u32, similarity: u16, nfiles: u16, old_file: DiffFile, new_file: DiffFile };
pub const StatusOptions = extern struct { version: c_uint = 1, show: c_int = 0, flags: c_uint = 1 | 16, pathspec: Strarray = .{}, baseline: ?*Tree = null, rename_threshold: u16 = 50 };
pub extern "git2" fn git_libgit2_init() c_int;
pub extern "git2" fn git_libgit2_shutdown() c_int;
pub extern "git2" fn git_libgit2_version(*c_int, *c_int, *c_int) void;
pub extern "git2" fn git_error_last() ?*const Error;
pub extern "git2" fn git_repository_open(**Repository, [*:0]const u8) c_int;
pub extern "git2" fn git_repository_open_ext(**Repository, [*:0]const u8, c_uint, ?[*:0]const u8) c_int;
pub extern "git2" fn git_repository_free(*Repository) void;
pub extern "git2" fn git_repository_workdir(*Repository) ?[*:0]const u8;
pub extern "git2" fn git_repository_path(*Repository) [*:0]const u8;
pub extern "git2" fn git_repository_commondir(*Repository) [*:0]const u8;
pub extern "git2" fn git_repository_state(*Repository) c_int;
pub extern "git2" fn git_repository_head(**Reference, *Repository) c_int;
pub extern "git2" fn git_reference_shorthand(*Reference) [*:0]const u8;
pub extern "git2" fn git_reference_target(*Reference) ?*const Oid;
pub extern "git2" fn git_reference_free(*Reference) void;
pub extern "git2" fn git_branch_upstream(**Reference, *Reference) c_int;
pub extern "git2" fn git_graph_ahead_behind(*usize, *usize, *Repository, *const Oid, *const Oid) c_int;
pub extern "git2" fn git_reference_list(*Strarray, *Repository) c_int;
pub extern "git2" fn git_remote_list(*Strarray, *Repository) c_int;
pub extern "git2" fn git_remote_lookup(**Remote, *Repository, [*:0]const u8) c_int;
pub extern "git2" fn git_remote_url(*const Remote) ?[*:0]const u8;
pub extern "git2" fn git_remote_free(*Remote) void;
pub extern "git2" fn git_strarray_dispose(*Strarray) void;
pub extern "git2" fn git_status_foreach(*Repository, *const fn ([*:0]const u8, c_uint, ?*anyopaque) callconv(.c) c_int, ?*anyopaque) c_int;
pub extern "git2" fn git_status_foreach_ext(*Repository, *const StatusOptions, *const fn ([*:0]const u8, c_uint, ?*anyopaque) callconv(.c) c_int, ?*anyopaque) c_int;
pub extern "git2" fn git_commit_lookup(**Commit, *Repository, *const Oid) c_int;
pub extern "git2" fn git_commit_tree(**Tree, *const Commit) c_int;
pub extern "git2" fn git_commit_summary(*const Commit) ?[*:0]const u8;
pub extern "git2" fn git_commit_author(*const Commit) *const Signature;
pub extern "git2" fn git_commit_parentcount(*const Commit) c_uint;
pub extern "git2" fn git_commit_parent(**Commit, *const Commit, c_uint) c_int;
pub extern "git2" fn git_commit_free(*Commit) void;
pub extern "git2" fn git_tree_free(*Tree) void;
