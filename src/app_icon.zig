//! Native desktop identity and window icons, separate from toolbar glyphs.
const std = @import("std");
const builtin = @import("builtin");
const Self = @This();

small: ?*anyopaque = null,
large: ?*anyopaque = null,

extern "shell32" fn SetCurrentProcessExplicitAppUserModelID([*:0]const u16) callconv(.winapi) i32;
extern "user32" fn LoadImageW(?*anyopaque, [*:0]const u16, u32, c_int, c_int, u32) callconv(.winapi) ?*anyopaque;
extern "user32" fn SendMessageW(*anyopaque, u32, usize, isize) callconv(.winapi) isize;
extern "user32" fn GetDpiForWindow(*anyopaque) callconv(.winapi) u32;
extern "user32" fn GetSystemMetricsForDpi(c_int, u32) callconv(.winapi) c_int;
extern "user32" fn DestroyIcon(*anyopaque) callconv(.winapi) c_int;

extern "kernel32" fn GetCurrentPackageFullName(*u32, ?[*]u16) callconv(.winapi) i32;

/// Must precede creating the window; matches the installed Windows shortcut.
pub fn prepare() !void {
    if (builtin.os.tag == .windows) {
        // A Microsoft Store (MSIX) install already has the identity of its package;
        // overriding it would detach the window from the Start and taskbar entry.
        var length: u32 = 0;
        const appmodel_error_no_package = 15700;
        if (GetCurrentPackageFullName(&length, null) != appmodel_error_no_package) return;
        if (SetCurrentProcessExplicitAppUserModelID(std.unicode.utf8ToUtf16LeStringLiteral("app.weaver.desktop")) < 0)
            return error.DesktopIdentityUnavailable;
    }
}

pub fn init(window: anytype) !Self {
    var self: Self = .{};
    errdefer self.deinit();
    switch (builtin.os.tag) {
        .windows => {
            const handle = window.getWindowHandle().windows;
            const dpi = GetDpiForWindow(handle.hwnd);
            // Group resource 1 is generated by scripts/generate-icons.py.
            // Separate owned handles avoid LR_SHARED reusing the first size.
            const resource = std.unicode.utf8ToUtf16LeStringLiteral("#1");
            self.small = LoadImageW(handle.hinstance, resource, 1, GetSystemMetricsForDpi(49, dpi), GetSystemMetricsForDpi(50, dpi), 0) orelse return error.AppIconUnavailable;
            self.large = LoadImageW(handle.hinstance, resource, 1, GetSystemMetricsForDpi(11, dpi), GetSystemMetricsForDpi(12, dpi), 0) orelse return error.AppIconUnavailable;
            _ = SendMessageW(handle.hwnd, 0x0080, 0, @bitCast(@intFromPtr(self.small.?)));
            _ = SendMessageW(handle.hwnd, 0x0080, 1, @bitCast(@intFromPtr(self.large.?)));
        },
        // Knots currently exposes no app-ID setter. This matches weaver.desktop,
        // allowing Wayland shells to resolve the packaged hicolor artwork.
        .linux => window.backend.state.toplevel.setAppId("weaver"),
        // macOS resolves the icon from Weaver.app/Contents/Resources/weaver.icns.
        else => {},
    }
    return self;
}

/// Call after destroying the window, which borrows the Windows handles.
pub fn deinit(self: *Self) void {
    if (builtin.os.tag == .windows) {
        if (self.small) |icon| _ = DestroyIcon(icon);
        if (self.large) |icon| _ = DestroyIcon(icon);
    }
    self.* = .{};
}
